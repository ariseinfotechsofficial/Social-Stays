export const villasIn = (destination: DestinationSlug) => villas.filter((v) => v.destination === destination);

/** Lowest weekday price among live villas in a destination */
export const startingPrice = (destination: DestinationSlug) =>
  Math.min(...villasIn(destination).filter((v) => v.status === "live").map((v) => v.priceFrom));

export const similarVillas = (villa: Villa, count = 3) =>
  liveVillas
    .filter((v) => v.slug !== villa.slug)
    .sort((a, b) => {
      const sameA = a.destination === villa.destination ? -1 : 0;
      const sameB = b.destination === villa.destination ? -1 : 0;
      return sameA - sameB || Math.abs(a.guests.max - villa.guests.max) - Math.abs(b.guests.max - villa.guests.max);
    })
    .slice(0, count);
